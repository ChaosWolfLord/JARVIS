class Opening(unittest.TestCase):
    def test_only_the_catalogue_entry_is_launched_never_the_users_words(self):
        a, launched = make()
        self.assertEqual(a.open("discord"), "Discord")
        self.assertEqual(launched, ["com.squirrel.Discord.Discord"])
        with self.assertRaises(apps.AppError):
            a.open(r"C:\Windows\System32\cmd.exe")
        with self.assertRaises(apps.AppError):
            a.open("discord & calc.exe")
        self.assertEqual(launched, ["com.squirrel.Discord.Discord"])

    def test_a_refused_app_launches_nothing(self):
        a, launched = make()
        for q in ("terminal", "powershell", "regedit", "windows powershell"):
            with self.assertRaises(apps.AppError):
                a.open(q)
        self.assertEqual(launched, [])

    def test_too_many_in_a_minute_stops(self):
        clock = [1000.0]
        a, launched = make(now=lambda: clock[0])
        for _ in range(6):
            a.open("notepad")
        with self.assertRaisesRegex(apps.AppError, "a lot of apps"):
            a.open("notepad")
        clock[0] += 61
        a.open("notepad")
        self.assertEqual(len(launched), 7)

    def test_a_launch_failure_is_explained(self):
        a = apps.Apps(catalogue_fn=lambda: CATALOGUE, running_fn=lambda: [], launch_fn=mock.Mock(side_effect=OSError("no")), config_path=Path(tempfile.mkdtemp()) / "c.json")
        with self.assertRaisesRegex(apps.AppError, "wouldn't start"):
            a.open("discord")


