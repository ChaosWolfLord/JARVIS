def make(tmp=None, **kw):
    folder = tmp or tempfile.mkdtemp()
    launched = []
    a = apps.Apps(catalogue_fn=lambda: [dict(r) for r in CATALOGUE], running_fn=lambda: [dict(r) for r in WINDOWS], launch_fn=launched.append,
                  config_path=Path(folder) / "apps.json", **kw)
    return a, launched


class TheList(unittest.TestCase):
    def test_ordinary_apps_are_openable(self):
        names = make()[0].names()
        for ok in ("Calculator", "Discord", "Google Chrome", "Notepad", "Spotify", "Microsoft Word"):
            self.assertIn(ok, names)

    def test_shells_admin_tools_installers_links_and_documents_never_are(self):
        names = set(make()[0].names())
        for bad in NEVER:
            self.assertNotIn(bad, names, bad)
        self.assertFalse([n for n in names if n.startswith("https")])

    def test_an_id_that_could_smuggle_a_command_is_refused(self):
        self.assertFalse(apps.safe_entry("Neat App", 'x" & calc.exe & "'))
        self.assertFalse(apps.safe_entry("Neat App", "a|b"))
        self.assertFalse(apps.safe_entry("Neat App", "a\nb"))
        self.assertTrue(apps.safe_entry("Neat App", "Vendor.NeatApp_abc!App"))

    def test_the_user_can_block_apps_or_allow_only_some(self):
        a, _ = make()
        a.config_path.write_text(json.dumps({"blocked": ["Discord", "spotify"]}), "utf-8")
        names = a.names()
        self.assertNotIn("Discord", names)
        self.assertNotIn("Spotify", names)
        self.assertIn("Calculator", names)
        a.config_path.write_text(json.dumps({"only": ["calculator", "Notepad", "Command Prompt"]}), "utf-8")
        self.assertEqual(sorted(a.names()), ["Calculator", "Notepad"])          # "only" can't add back what is never allowed

    def test_a_damaged_config_is_ignored(self):
        a, _ = make()
        a.config_path.write_text("{oops", "utf-8")
        self.assertIn("Calculator", a.names())
        a.config_path.write_text('["a list"]', "utf-8")
        self.assertIn("Calculator", a.names())


