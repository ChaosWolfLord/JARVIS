class Closing(unittest.TestCase):
    def prepare(self, query="", pid=None):
        a, _ = make()
        with mock.patch.object(fixes, "prepare_end_program", side_effect=lambda p, **k: fixes.Prepared(f"close {p}", f"preview {p}", lambda: "closed")) as end:
            prepared = a.prepare_close(query, pid)
        return prepared, end

    def test_a_named_program_gets_an_allow_card_and_is_not_closed(self):
        prepared, end = self.prepare("spotify")
        end.assert_called_once_with("400")
        self.assertEqual(prepared.preview, "preview 400")

    def test_title_matches_work_and_several_matches_ask_which(self):
        self.assertEqual(self.prepare("discord")[0].title, "close 100")
        with self.assertRaisesRegex(apps.AppError, "several programs"):
            self.prepare("chrome")
        self.assertEqual(self.prepare(pid=501)[0].title, "close 501")

    def test_jarvis_windows_and_unknown_programs_cant_be_closed(self):
        for q, pid in (("jarvis", None), ("", 200), ("", 300), ("nothing like this", None), ("", "abc"), ("", 99999), ("", None)):
            with self.assertRaises(apps.AppError, msg=str((q, pid))):
                self.prepare(q, pid)

    def test_the_card_text_comes_from_the_real_close_checks(self):
        a, _ = make()
        with mock.patch.object(fixes.diagnostics, "powershell_json", return_value={"name": "svchost", "id": 100, "session": 1, "mb": 5, "path": ""}), \
                self.assertRaisesRegex(apps.AppError, "part of Windows"):
            a.prepare_close("", 100)


class WindowsStoreApps(unittest.TestCase):
    """Calculator, Settings and similar share one host process. Closing must close that one window, never the host (it carries other apps' windows)."""

    def setUp(self):
        self.windows = [dict(w) for w in WINDOWS]
        self.closed = []
        self.a = apps.Apps(catalogue_fn=lambda: CATALOGUE, running_fn=lambda: [dict(w) for w in self.windows], launch_fn=lambda i: None,
                           config_path=Path(tempfile.mkdtemp()) / "c.json", close_window_fn=self.closed.append)
        patch = mock.patch.object(apps.time, "sleep")
        patch.start()
        self.addCleanup(patch.stop)

    def test_they_are_listed_by_their_window_not_by_the_host(self):
        row = next(r for r in self.a.running() if r["id"] == 600)
        self.assertEqual((row["name"], row["hosted"]), ("Calculator", True))
        self.assertFalse(any("applicationframehost" in r["name"].lower() for r in self.a.running()))

    def test_closing_asks_the_window_nicely_and_never_ends_the_host(self):
        with mock.patch.object(fixes, "prepare_end_program", side_effect=AssertionError("the host process must never be ended")),                 mock.patch.object(fixes.subprocess, "run", side_effect=AssertionError("no taskkill for a hosted window")):
            prepared = self.a.prepare_close("calculator")
            self.assertEqual(prepared.title, "JARVIS wants to close Calculator")
            self.assertIn("as if you pressed its X", prepared.preview)
            self.assertIn("never forced", prepared.preview)
            self.windows = [w for w in self.windows if w["id"] != 600]               # the window goes away once asked
            self.assertEqual(prepared.run(), "Closed Calculator.")
        self.assertEqual(self.closed, [600])

    def test_a_window_that_stays_open_is_not_forced(self):
        prepared = self.a.prepare_close("calculator")
        result = prepared.run()
        self.assertTrue(result.startswith("Error"))
        self.assertIn("won't force", result)

    def test_the_host_process_is_protected_everywhere(self):
        self.assertIn("applicationframehost", fixes.PROTECTED)
        info = json.dumps({"name": "ApplicationFrameHost", "id": 600, "session": 1, "mb": 50, "path": ""})
        with self.assertRaisesRegex(fixes.FixError, "part of Windows"):
            fixes.prepare_end_program("600", run=lambda script: info, own_session=1, supervisor_pid=999_999)


class Speaking(unittest.TestCase):
    def test_what_counts_as_an_open_command(self):
        for text, target in (("Jarvis, open Discord", "discord"), ("launch the calculator app", "calculator"), ("please open my notepad", "notepad"),
                             ("start spotify", "spotify"), ("open up Google Chrome", "google chrome")):
            self.assertEqual(apps.parse_command(text), target, text)

    def test_widgets_questions_and_other_talk_are_left_alone(self):
        for text in ("open the weather", "start a timer", "start the music", "open the lights", "what apps can you open", "can i open discord",
                     "close discord", "run cmd", "play something", "open settings", "open"):
            self.assertIsNone(apps.parse_command(text), text)

    def test_voice_opens_known_apps_and_hands_back_the_rest(self):
        a, launched = make()
        with mock.patch.dict("os.environ", {"JARVIS_SNARK": "0"}):
            out = apps.handle_voice("open discord", a)
        self.assertEqual((out["handled"], out["ok"], out["text"]), (True, True, "Opening Discord."))
        self.assertEqual(launched, ["com.squirrel.Discord.Discord"])
        self.assertFalse(apps.handle_voice("open the spaceship", a)["handled"])          # no such app: the AI can answer
        refused = apps.handle_voice("open powershell", a)
        self.assertFalse(refused["handled"])                                             # and it still can't be opened
        self.assertEqual(launched, ["com.squirrel.Discord.Discord"])
        ambiguous = apps.handle_voice("open minecraft", a)
        self.assertTrue(ambiguous["handled"] and not ambiguous["ok"])


def scripted(rounds):
    answers = iter(rounds)

    def fake(msgs, cancel=None):
        text, calls = next(answers)
        r = agent._Round()
        r.text = text
        r.calls = {i: {"id": f"c{i}", "name": n, "args": json.dumps(a), "extra": {}} for i, (n, a) in enumerate(calls)}
        if text:
            yield {"type": "text", "delta": text}
        yield {"type": "_round", "target": agent.Target("openrouter", "t:free"), "round": r}
    return fake


class InTheAgent(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.a, self.launched = make(tmp.name)
        for patch in (mock.patch.object(audit, "LOG_FILE", Path(tmp.name) / "a.log"), mock.patch.object(agent.store, "MEMORY_FILE", Path(tmp.name) / "m.json"),
                      mock.patch.object(apps, "apps", self.a)):
            patch.start()
            self.addCleanup(patch.stop)

    def turn(self, rounds, private=False, allow=True, prepared=None):
        target = agent.Target("openrouter", "t:free")
        extra = [mock.patch.object(fixes, "prepare_end_program", return_value=prepared)] if prepared else []
        for patch in extra:
            patch.start()
            self.addCleanup(patch.stop)
        with mock.patch.object(agent, "_run_round", scripted(rounds)), mock.patch.object(agent, "CHAIN", [target]), mock.patch.object(agent, "usable", return_value=[target]), \
                mock.patch.object(agent, "_refresh_chain"), mock.patch.object(agent, "_openrouter_notice", return_value=None), \
                mock.patch.object(agent.runner, "wait", return_value=allow):
            return list(agent.chat_turn("q", [], None, private=private))

    def test_the_tools_are_registered_and_closing_always_asks(self):
        self.assertIn("app_close", agent.ACTION_TOOLS)
        self.assertNotIn("apps", agent.ACTION_TOOLS)
        names = {t["function"]["name"] for t in agent.active_tools()}
        self.assertTrue({"apps", "app_close"} <= names)
        with mock.patch.dict("os.environ", {"JARVIS_APPS": "0"}):
            self.assertFalse({"apps", "app_close"} & {t["function"]["name"] for t in agent.active_tools()})
        self.assertEqual(agent._step_text("apps", {}), "Checking apps")

    def test_opening_is_free_until_private_data_has_been_read(self):
        events = self.turn([("", [("apps", {"action": "open", "name": "calculator"})]), ("Opened.", [])])
        self.assertEqual(self.launched, ["Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"])
        self.assertFalse(any(e["type"] == "run_request" for e in events))

    def test_after_reading_mail_opening_an_app_needs_a_click(self):
        rounds = [("", [("gmail_search", {"query": "x"})]), ("", [("apps", {"action": "open", "name": "calculator"})]), ("ok", [])]
        with mock.patch.object(agent, "_run_lookup", side_effect=lambda n, a: apps.tool(a, self.a) if n == "apps" else "mail"):
            declined = self.turn(rounds, allow=False)
        self.assertEqual(self.launched, [])                                             # an instruction hidden in an email can't start anything
        card = next(e for e in declined if e["type"] == "run_request")
        self.assertIn("open an app", card["title"])
        self.assertIn("calculator", card["code"])
        with mock.patch.object(agent, "_run_lookup", side_effect=lambda n, a: apps.tool(a, self.a) if n == "apps" else "mail"):
            self.turn(rounds, allow=True)
        self.assertEqual(len(self.launched), 1)                                         # allowed this time

    def test_listing_apps_after_private_data_needs_no_click(self):
        with mock.patch.object(agent, "_run_lookup", side_effect=lambda n, a: "mail" if n == "gmail_search" else "list"):
            events = self.turn([("", [("gmail_search", {"query": "x"})]), ("", [("apps", {"action": "running"})]), ("ok", [])])
        self.assertFalse(any(e["type"] == "run_request" for e in events))

    def test_closing_shows_the_card_and_does_nothing_when_declined(self):
        ran = mock.Mock(return_value="Closed Discord.")
        prepared = fixes.Prepared("JARVIS wants to close Discord", "Closes Discord, process 100.", ran)
        events = self.turn([("", [("app_close", {"name": "discord"})]), ("done", [])], allow=False, prepared=prepared)
        ran.assert_not_called()
        card = next(e for e in events if e["type"] == "run_request")
        self.assertEqual((card["title"], card["code"]), ("JARVIS wants to close Discord", "Closes Discord, process 100."))

    def test_closing_runs_once_when_allowed(self):
        ran = mock.Mock(return_value="Closed Discord.")
        self.turn([("", [("app_close", {"name": "discord"})]), ("done", [])], allow=True, prepared=fixes.Prepared("t", "p", ran))
        ran.assert_called_once()

    def test_closing_the_jarvis_window_never_reaches_the_user(self):
        with mock.patch.object(agent.runner, "request") as asked:
            events = list(agent._run_action("app_close", {"name": "jarvis"}))
        asked.assert_not_called()
        self.assertTrue(events[-1].startswith("Error"))

    def test_main_routes(self):
        from server import main
        with mock.patch.object(apps, "apps", self.a), mock.patch.object(main.apps_mod, "apps", self.a):
            self.assertIn("Discord", main.get_apps()["apps"])
            self.assertNotIn(200, [r["id"] for r in main.get_apps()["running"]])           # JARVIS's own window is never listed
            self.assertTrue(main.voice_apps(main.SpokenLight(text="open notepad"))["handled"])
            self.assertFalse(main.voice_apps(main.SpokenLight(text="start a timer"))["handled"])
            self.assertEqual(self.launched, [r"{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}\notepad.exe"])


